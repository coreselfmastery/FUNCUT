#!/usr/bin/env python3
"""The motion gallery: twenty effects as clips, from their own shaders.

docs/SHADER_GALLERY.md is generated by this script and committed: for
each package in THE_TWENTY it links the clip scripts/shader-clips.sh
recorded (`concat-cli clip`, the package's own shader drawing every
frame on the GPU, the same reference plate every card is drawn from,
the plate drifting under the effect, and one knob swept floor to
ceiling where a static look shows at speed only when its knob
travels), reads the package's own manifest for its name, category and
one-line description, and carries the honest "needs tuning" note.

A clip that is missing is a row that says so, never a broken link: the
gallery refuses to publish what a reviewer cannot watch.

Run after recording:  python3 scripts/shader-gallery.py
"""
import pathlib
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PACKAGES = ROOT / "src/crates/concat-effects/packages"
CLIPS = ROOT / "docs/clips"
OUT = ROOT / "docs/SHADER_GALLERY.md"

# The gallery's editorial choice, recorded by scripts/shader-clips.sh:
# (package id, the knob the clip sweeps, the honest "needs tuning" note).
# The notes say what a designer should know before committing the look,
# grounded in what the package itself declares - a fixed beat, a one-shot
# shape, a look that wants a certain plate.
THE_TWENTY = [
    ("concat.film", "grain",
     "grain at 100 is a stock of its own; most plates want 30-50"),
    ("concat.vhs", "bleed",
     "runs at defaults; bleed past 80 smears small text"),
    ("concat.teal-orange", "amount",
     "skin is held by design; push `skin` past 70 on close-ups"),
    ("concat.film-grain", "",
     "runs at defaults; the grain is the whole package, so pick its amount for the platform"),
    ("concat.fire-flicker", "",
     "wants a warm-lit plate to flicker; neutral daylight reads as noise"),
    ("concat.film-scratch", "",
     "runs at defaults; pair with film-grain or it reads as interference"),
    ("concat.bloom-pulse", "",
     "wants bright highlights to breathe on; a flat plate shows nothing"),
    ("concat.chromatic-pulse", "",
     "runs at defaults; keep clips short or the breathing reads as a codec fault"),
    ("concat.earthquake", "",
     "two jolts with brightness slams: trim the clip to the hit, not around it"),
    ("concat.embers-rise", "",
     "reads best over dark plates; embers vanish into a bright sky"),
    ("concat.fireflies", "",
     "reads best over dark plates; a summer dusk, not an office"),
    ("concat.dust-motes", "",
     "wants a bright shaft in the plate to hang the specks in"),
    ("concat.falling-dust", "",
     "the CPU path draws the fade and a whisper of noise; the dust is GPU-only"),
    ("concat.fisheye", "strength",
     "the bulge eats the edges: leave headroom at the sides of the plate"),
    ("concat.anime-speed-focus", "",
     "wants a centred subject; off-centre compositions drift out of the focus"),
    ("concat.beat-pulse", "",
     "lands on a fixed 120 bpm - retime the edit to it or it fights the music"),
    ("concat.cyberpunk", "intensity",
     "reads on night streets and signage; heavy on skin - keep faces lit neutral"),
    ("concat.noir", "intensity",
     "the corners dim hard: keep titles inside the middle two-thirds"),
    ("concat.dreamy", "intensity",
     "wants pastel sources; it muddies saturated reds"),
    ("concat.neon", "glow",
     "signage and lights bloom while faces stay clean; glow past 80 haloes everything"),
]


def manifest_of(package_id):
    folder = PACKAGES / package_id
    manifest = folder / "effect.toml"
    if not manifest.is_file():
        return None
    return tomllib.loads(manifest.read_text(encoding="utf-8"))


def rows():
    for package_id, sweep, note in THE_TWENTY:
        manifest = manifest_of(package_id)
        if manifest is None:
            yield {"id": package_id, "missing": "no such package"}
            continue
        effect = manifest.get("effect", {})
        # The clip's file name is the package id's own suffix, the way
        # scripts/shader-clips.sh records it: `concat.film` -> `film.mp4`.
        file = f"{package_id.split('.', 1)[-1]}.mp4"
        clip = CLIPS / file
        yield {
            "id": package_id,
            "name": effect.get("name", package_id),
            "category": effect.get("category", ""),
            "description": effect.get("description", ""),
            "sweep": sweep,
            "note": note,
            "clip": f"clips/{file}",
            "there": clip.is_file() and clip.stat().st_size > 0,
            "missing": "" if clip.is_file() else "not recorded - run scripts/shader-clips.sh",
        }


def main():
    out = [
        "# The motion gallery: twenty effects as clips",
        "",
        "docs/EFFECTS-GALLERY.md shows every picture package as a still, before and after.",
        "This page shows twenty of them **in motion, at speed**: each clip is the same",
        "reference plate drifting under the package's own shader, drawn frame by frame on",
        "the GPU by `concat-cli clip` (`scripts/shader-clips.sh` records them) - so the",
        "grain dances, the pulse breathes, the embers climb, and a static look is shown",
        "with the knob named in its row swept floor to ceiling. The plate carries no",
        "audio, and neither do the clips: the gallery shows the look, not the mix.",
        "",
        "A reviewer can watch every clip below without building the project.",
        "",
        "| Effect | Category | Clip | What it does | Needs tuning |",
        "| --- | --- | --- | --- | --- |",
    ]
    for row in rows():
        if "missing" in row and "no such package" in row.get("missing", ""):
            out.append(
                f"| `{row['id']}` | - | - | THE PACKAGE IS GONE - update THE_TWENTY | - |"
            )
            continue
        clip = f"[▶ {row['name']}]({row['clip']})"
        sweep = (
            f" (sweeping `{row['sweep']}`)"
            if row["sweep"]
            else ""
        )
        tuning = row["note"] if row["there"] else f"**{row['missing']}**"
        out.append(
            f"| **{row['name']}** | {row['category']} | {clip}{sweep} |"
            f" {row['description']} | {tuning} |"
        )
    out += [
        "",
        "The `needs tuning` column is the honest note: what a designer should know before",
        "committing the look, grounded in what the package itself declares - a fixed beat,",
        "a one-shot shape, a look that wants a certain plate. `runs at defaults` means the",
        "package's own defaults are the look, and the clip shows exactly that.",
        "",
        "To record them again (a new package, a new still, a new plate drift):",
        "",
        "```sh",
        "scripts/shader-clips.sh           # draws every clip on the GPU",
        "python3 scripts/shader-gallery.py # regenerates this page from the manifests",
        "```",
        "",
        "One clip, by hand, with a knob swept and the plate held still:",
        "",
        "```sh",
        "cargo build -p concat-cli --bin concat-cli",
        "./src/target/debug/concat-cli clip concat.vhs --out docs/clips/vhs.mp4 \\",
        "    --sweep bleed --drift 0",
        "```",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8")
    there = sum(1 for row in rows() if row.get("there"))
    print(f"{OUT} written; {there} of {len(THE_TWENTY)} clips present")


if __name__ == "__main__":
    main()
