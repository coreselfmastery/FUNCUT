# Records the shader gallery's clips: twenty packages, each drawn by its
# own shader on the GPU through `concat-cli clip` - the effect in motion,
# at speed, over the same reference plate every card is drawn from. The
# clips land in docs/clips/, which docs/SHADER_GALLERY.md links; a
# reviewer can watch them without building anything.
#
# Run from a checkout with a GPU (or a software Vulkan device such as
# lavapipe):  scripts/shader-clips.sh [path-to-concat-cli]
#
# The table itself is generated by scripts/shader-gallery.py, which reads
# each package's own manifest for its description and refuses to publish
# a clip that is missing.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/docs/clips"
mkdir -p "$out"

if [ $# -ge 1 ]; then
  cli="$1"
else
  echo "building concat-cli..." >&2
  (cd "$root/src" && cargo build -p concat-cli --bin concat-cli) >&2
  cli="$root/src/target/debug/concat-cli"
fi

# The twenty: id, and the knob swept floor-to-ceiling over the clip when
# a static look shows at speed only when its knob travels. The list is
# the gallery's editorial choice; scripts/shader-gallery.py holds the
# same ids with their descriptions and tuning notes.
clips=(
  "concat.film|grain"
  "concat.vhs|bleed"
  "concat.teal-orange|amount"
  "concat.film-grain|"
  "concat.fire-flicker|"
  "concat.film-scratch|"
  "concat.bloom-pulse|"
  "concat.chromatic-pulse|"
  "concat.earthquake|"
  "concat.embers-rise|"
  "concat.fireflies|"
  "concat.dust-motes|"
  "concat.falling-dust|"
  "concat.fisheye|strength"
  "concat.anime-speed-focus|"
  "concat.beat-pulse|"
  "concat.cyberpunk|intensity"
  "concat.noir|intensity"
  "concat.dreamy|intensity"
  "concat.neon|glow"
)

count=0
for entry in "${clips[@]}"; do
  id="${entry%%|*}"
  sweep="${entry#*|}"
  name="${id#concat.}.mp4"
  args=(clip "$id" --out "$out/$name" --seconds 2 --fps 24 --width 480 --height 270 --drift 0.06)
  if [ -n "$sweep" ]; then
    args+=(--sweep "$sweep")
  fi
  echo "recording $id${sweep:+ (sweeping $sweep)}" >&2
  "$cli" "${args[@]}" >/dev/null
  count=$((count + 1))
done

echo "recorded $count clips into $out ($(du -sh "$out" | cut -f1))" >&2
echo "now run: python3 scripts/shader-gallery.py" >&2
