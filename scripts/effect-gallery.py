#!/usr/bin/env python3
"""The before/after gallery of every picture package, from its own card.

docs/EFFECTS-GALLERY.md is generated by this script and committed: it
shows the one reference plate every card is drawn from (the "before"),
then every shipped card (the "after") - a card being that plate through
the package's own shader at its defaults, drawn by the same compositor a
clip's frames go through (src/crates/concat-host/src/cards.rs), and the
shipped cards being real GPU draws bundled by scripts/bundle-cards.sh.

Run after bundling new cards:  python3 scripts/effect-gallery.py
"""
import pathlib
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PACKAGES = ROOT / "src/crates/concat-effects/packages"
CARDS = ROOT / "src/crates/concat/cards"
PLATE = "../src/crates/concat-host/assets/card-still.jpg"
OUT = ROOT / "docs/EFFECTS-GALLERY.md"

KINDS = [
    ("filter", "Filters", "The colour and look grades, over the whole picture."),
    ("effect", "Effects", "The stickers, glows, glitches and frames, over the whole picture."),
    ("transition", "Transitions", "The cut halfway through, from the plate to a mirrored, hue-turned copy of it."),
]


def picture_packages():
    out = []
    for folder in sorted(PACKAGES.iterdir()):
        manifest = folder / "effect.toml"
        if not manifest.is_file():
            continue
        effect = tomllib.loads(manifest.read_text(encoding="utf-8")).get("effect", {})
        if effect.get("kind") not in {kind for kind, _, _ in KINDS}:
            continue
        out.append(
            {
                "id": effect.get("id", folder.name),
                "name": effect.get("name", folder.name),
                "kind": effect.get("kind"),
                "category": effect.get("category", ""),
                "order": effect.get("order", 0),
                "description": effect.get("description", ""),
                "card": (CARDS / f"{effect.get('id', folder.name)}.jpg").is_file(),
            }
        )
    return out


def grid(entries):
    cells = []
    for entry in entries:
        src = f"../src/crates/concat/cards/{entry['id']}.jpg"
        alt = entry["description"].replace('"', "&quot;") or entry["name"]
        cells.append(
            f'<td align="center" width="33%"><p><b>{entry["name"]}</b><br>'
            f'<sub>{entry["category"]} - {alt}</sub><br>'
            f'<a href="../src/crates/concat/cards/{entry["id"]}.jpg">'
            f'<img src="{src}" alt="{alt}" width="320"></a></p></td>'
        )
    rows = []
    for start in range(0, len(cells), 3):
        row = cells[start : start + 3]
        while len(row) < 3:
            row.append("<td></td>")
        rows.append("  <tr>" + "".join(row) + "</tr>")
    return "<table>\n" + "\n".join(rows) + "\n</table>"


def main():
    packages = picture_packages()
    with_card = [p for p in packages if p["card"]]
    without = [p for p in packages if not p["card"]]

    page = [
        "# The effects gallery: every picture package, before and after",
        "",
        "Every card below is the **same reference plate**, drawn through a",
        "package's own shader at that package's defaults, by the same",
        "compositor a clip's frames go through - not a mock-up and not a",
        "screenshot of another app. The cards that ship were drawn on a real",
        "GPU and bundled out of a run of the app itself",
        "(`scripts/bundle-cards.sh`); this page is generated from the",
        "packages and those cards by `scripts/effect-gallery.py`, and is",
        "committed so it can be read without building anything.",
        "",
        f"**The plate - the before, and what every card below was drawn",
        f"from:**",
        "",
        f'<a href="{PLATE}"><img src="{PLATE}" alt="The reference plate" width="640"></a>',
        "",
    ]

    for kind, title, blurb in KINDS:
        entries = sorted(
            (p for p in with_card if p["kind"] == kind),
            key=lambda p: (p["category"], p["order"], p["name"]),
        )
        page += [f"## {title} ({len(entries)})", "", blurb, "", grid(entries), ""]

    if without:
        page += ["## Packages without a shipped card", ""]
        page += [
            f"- **{p['name']}** ({p['id']}): {p['description']}"
            for p in sorted(without, key=lambda p: p["name"])
        ]
        page += [""]

    page += [
        "## The audio packages",
        "",
        "The 25 audio packages are not pictures and have no cards: their",
        "knobs and what they do are listed in the Audio shelf in the app,",
        "and their FFmpeg chains are their packages' own files.",
        "",
        "---",
        "",
        "Regenerate this page after bundling cards:",
        "`python3 scripts/effect-gallery.py`.",
        "",
    ]

    OUT.write_text("\n".join(page), encoding="utf-8")
    print(f"{OUT}: {len(with_card)} cards, {len(without)} without")


if __name__ == "__main__":
    main()
